# LeetCode 88. 合并两个有序数组
#
# 题目：
# 给定两个按非递减顺序排列的整数数组 nums1 和 nums2，
# 将 nums2 合并到 nums1 中，使合并后的数组仍然按非递减顺序排列。
#
# nums1 的长度为 m + n：
# 前 m 个元素是真正的数据，后 n 个位置是预留的空位（用 0 表示）。
#
# 例如：
# nums1 = [1, 2, 3, 0, 0, 0], m = 3
# nums2 = [2, 5, 6], n = 3
#
# 最终：
# nums1 = [1, 2, 2, 3, 5, 6]


class Solution:

    # ==========================================================
    # 方法一：直接合并 + 排序
    # ==========================================================
    #
    # 思路：
    # nums1 的前 m 个元素才是真正的数据，
    # 后面的 n 个位置本来就是给 nums2 预留的。
    #
    # 所以可以直接把 nums2 放到 nums1 的后 n 个位置，
    # 然后对整个 nums1 进行排序。
    #
    # 关键代码：
    # nums1[m:] = nums2
    #
    # 例如：
    # nums1 = [1, 2, 3, 0, 0, 0]
    # nums2 = [2, 5, 6]
    #
    # nums1[m:] 表示 nums1[3:]：
    # [0, 0, 0]
    #
    # 执行：
    # nums1[m:] = nums2
    #
    # 变成：
    # [1, 2, 3, 2, 5, 6]
    #
    # 然后：
    # nums1.sort()
    #
    # 得到：
    # [1, 2, 2, 3, 5, 6]
    #
    # 优点：
    # 写法非常简单，容易理解。
    #
    # 缺点：
    # 两个数组本身已经是有序的，却又重新进行了一次排序，
    # 没有充分利用题目给出的“有序”条件。
    #
    # 时间复杂度：O((m+n)log(m+n))
    # 空间复杂度：通常记为 O(1) 额外空间（原地排序）
    #
    # 注意：
    # 这里使用切片是为了理解题目。
    # LeetCode 最终要求直接修改 nums1，不需要 return。
    #
    def merge_sort(self, nums1, m, nums2, n):
        nums1[m:] = nums2
        nums1.sort()


    # ==========================================================
    # 方法二：双指针，从后往前合并（优化）
    # ==========================================================
    #
    # 为什么可以优化？
    #
    # 题目已经告诉我们：
    # nums1 和 nums2 本身都是有序的。
    #
    # 例如：
    #
    # nums1：[1, 2, 3, 0, 0, 0]
    # nums2：[2, 5, 6]
    #
    # 我们没有必要把它们混在一起之后再排序。
    #
    # 可以直接利用它们已经有序的特点：
    # 每次比较两个数组当前最大的数字，
    # 把较大的数字放到 nums1 最后面的空位。
    #
    # 为什么从后往前？
    #
    # 因为 nums1 后面本来就是空位：
    #
    # [1, 2, 3, 0, 0, 0]
    #            ↑
    #          空位
    #
    # 最终最大的数字应该放在最后面。
    #
    # 所以我们从最后一个位置开始往前填。
    #
    #
    # 三个指针：
    #
    # i：指向 nums1 有效数据的最后一个元素
    # j：指向 nums2 最后一个元素
    # k：指向 nums1 最后一个位置
    #
    # 例如：
    #
    # nums1 = [1, 2, 3, 0, 0, 0]
    #              ↑        ↑
    #              i        k
    #
    # nums2 = [2, 5, 6]
    #              ↑
    #              j
    #
    # 初始：
    # i = m - 1
    # j = n - 1
    # k = m + n - 1
    #
    #
    # 每次比较：
    #
    # nums1[i] 和 nums2[j]
    #
    # 谁大，就把谁放到 nums1[k]。
    #
    # 然后：
    # 对应的 i 或 j 向前移动一位
    # k 也向前移动一位
    #
    # 例如：
    #
    # nums1[i] = 3
    # nums2[j] = 6
    #
    # 6 更大：
    #
    # nums1[k] = 6
    #
    # 然后：
    # j -= 1
    # k -= 1
    #
    #
    # 为什么最后只需要检查 nums2？
    #
    # 因为如果 nums2 已经全部放完，
    # nums1 剩下的元素本来就在正确的位置。
    #
    # 例如：
    #
    # nums1 = [1, 2, 3, 0, 0, 0]
    # nums2 = [4, 5, 6]
    #
    # 最后会得到：
    # [1, 2, 3, 4, 5, 6]
    #
    # nums2 用完后，nums1 中剩下的 1、2、3
    # 已经在正确的位置，不需要再处理。
    #
    # 但是如果 nums2 还有元素没有放完，
    # 就必须继续把 nums2 剩余元素复制到 nums1。
    #
    # 时间复杂度：O(m+n)
    # 空间复杂度：O(1)
    #
    def merge(self, nums1, m, nums2, n):

        # i 指向 nums1 中有效数据的最后一个元素
        i = m - 1

        # j 指向 nums2 的最后一个元素
        j = n - 1

        # k 指向 nums1 最后面的空位
        k = m + n - 1

        # 当两个数组都还有元素时，继续比较
        while i >= 0 and j >= 0:

            # 如果 nums1 当前元素更大
            if nums1[i] > nums2[j]:

                # 把较大的元素放到 nums1 最后面
                nums1[k] = nums1[i]

                # nums1 指针向前移动
                i -= 1

            else:

                # nums2 当前元素更大或相等
                nums1[k] = nums2[j]

                # nums2 指针向前移动
                j -= 1

            # nums1 的填充位置向前移动
            k -= 1

        # 如果 nums2 还有元素没有放完，
        # 直接复制到 nums1 剩余位置
        while j >= 0:
            nums1[k] = nums2[j]

            j -= 1
            k -= 1


# ==========================================================
# 本题总结
# ==========================================================
#
# 方法一：
# nums1[m:] = nums2
# nums1.sort()
#
# 思路简单，但没有利用两个数组“已经有序”的特点。
#
# 时间复杂度：O((m+n)log(m+n))
# 空间复杂度：O(1) 额外空间
#
#
# 方法二：
# 使用三个指针，从后往前比较两个数组中的最大值。
#
# i → nums1 有效数据的最后一个位置
# j → nums2 最后一个位置
# k → nums1 最后一个位置
#
# 每次把 nums1[i] 和 nums2[j] 中较大的数字放到 nums1[k]。
#
# 时间复杂度：O(m+n)
# 空间复杂度：O(1)
#
# 核心思想：
# 两个数组已经有序
#        ↓
# 不需要重新排序
#        ↓
# 从后往前比较最大值
#        ↓
# 把较大的数放到最后
#
# 这就是本题的双指针思想。